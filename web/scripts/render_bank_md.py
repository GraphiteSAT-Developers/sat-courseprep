"""Render the item bank as readable Markdown pages for GitHub.

Writes docs/question-bank/README.md (index with counts) and one page per
official skill, grouped by domain. Each question shows the stem, choices,
answer, by-hand solution and Desmos route. GitHub renders the $...$ math.

usage: python3 web/scripts/render_bank_md.py
"""

from __future__ import annotations

import re
from collections import Counter, defaultdict
from fractions import Fraction
from pathlib import Path

from itembank import DOMAINS, load_items

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "question-bank"

DOMAIN_TITLES = {
    "algebra": "Algebra",
    "advanced-math": "Advanced Math",
    "psda": "Problem-Solving and Data Analysis",
    "geometry-trig": "Geometry and Trigonometry",
}
DIFF_ORDER = {"easy": 0, "medium": 1, "hard": 2}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def fmt_answer(a: Fraction) -> str:
    if a.denominator == 1:
        return f"{a.numerator}"
    dec = a.numerator / a.denominator
    return f"{a.numerator}/{a.denominator} (≈ {dec:.4g})"


def md_escape_prose(text: str) -> str:
    # Keep $...$ math intact; escape characters GitHub would read as Markdown outside math.
    parts = re.split(r"(\$[^$]+\$)", text)
    out = []
    for p in parts:
        if p.startswith("$") and p.endswith("$") and len(p) > 1:
            out.append(p)
        else:
            out.append(p.replace("*", "\\*").replace("_", "\\_"))
    return "".join(out)


def render_item(n: int, it: dict) -> str:
    fmt = "Multiple choice" if it["format"] == "mc" else "Student-produced response"
    tech = ", ".join(it["techniques"]) or "—"
    lines = [
        f"### {n}. {it['id']}",
        "",
        f"*{it['difficulty'].capitalize()} · {fmt} · route: {it['route']} · techniques: {tech}*",
        "",
        md_escape_prose(it["stem"]),
        "",
    ]
    if it["format"] == "mc":
        for j, c in enumerate(it["choices"]):
            lines.append(f"- **{'ABCD'[j]}.** {md_escape_prose(c)}")
        lines += ["", f"**Answer:** {'ABCD'[it['answerIndex']]}"]
    else:
        lines.append("**Answer:** " + " or ".join(fmt_answer(a) for a in it["answers"]))
    lines += ["", "<details><summary>Solutions</summary>", ""]
    lines += [f"**By hand.** {md_escape_prose(it['byHand'])}", ""]
    if it.get("desmos"):
        d = it["desmos"]
        typed = "<br>".join(f"<code>{l.replace('<', '&lt;').replace('>', '&gt;')}</code>" for l in d["lines"])
        status = "verified" if d["verified"] else "not yet verified in Desmos"
        lines += [f"**Desmos** ({status}). Type:<br>{typed}", "", md_escape_prose(d["read"]), ""]
    lines += ["</details>", "", "---", ""]
    return "\n".join(lines)


def main() -> int:
    items = load_items()
    by_skill: dict[str, list[dict]] = defaultdict(list)
    skill_domain: dict[str, str] = {}
    for it in items:
        by_skill[it["skill"]].append(it)
        skill_domain[it["skill"]] = it["domain"]

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        old.unlink()

    index = [
        "# SAT Math question bank",
        "",
        f"{len(items)} original questions, written to the College Board Digital SAT Math specifications "
        "(`docs/item-style-guide.md`). Every answer key is recomputed with SymPy (`web/scripts/verify_items.py`) "
        "and every item passes the style lint (`web/scripts/lint_items.py`). Desmos routes are not yet verified "
        "in a live calculator.",
        "",
        "Generated by `python3 web/scripts/render_bank_md.py` from `web/content/items.ts`; do not edit these pages by hand.",
        "",
        "*SAT® is a trademark registered by the College Board, which is not affiliated with, and does not endorse, this product.*",
        "",
    ]
    fmt = Counter(i["format"] for i in items)
    diff = Counter(i["difficulty"] for i in items)
    index += [
        f"**Format:** {fmt['mc']} multiple choice, {fmt['spr']} student-produced response. "
        f"**Difficulty:** {diff['easy']} easy, {diff['medium']} medium, {diff['hard']} hard.",
        "",
    ]
    for dom in DOMAINS:
        skills = sorted(s for s, d in skill_domain.items() if d == dom)
        total = sum(len(by_skill[s]) for s in skills)
        index += [f"## {DOMAIN_TITLES[dom]} ({total})", "", "| Skill | Items | Easy | Medium | Hard |", "|---|---|---|---|---|"]
        for s in skills:
            c = Counter(i["difficulty"] for i in by_skill[s])
            fname = f"{slug(dom)}--{slug(s)}.md"
            index.append(f"| [{s}]({fname}) | {len(by_skill[s])} | {c['easy']} | {c['medium']} | {c['hard']} |")
            page_items = sorted(by_skill[s], key=lambda i: (DIFF_ORDER[i["difficulty"]], i["id"]))
            page = [
                f"# {s}",
                "",
                f"[← Question bank index](README.md) · {DOMAIN_TITLES[dom]} · {len(page_items)} questions, easiest first",
                "",
            ]
            page += [render_item(n, it) for n, it in enumerate(page_items, 1)]
            (OUT / fname).write_text("\n".join(page), encoding="utf-8")
        index.append("")
    (OUT / "README.md").write_text("\n".join(index), encoding="utf-8")
    print(f"wrote {len(by_skill) + 1} pages, {len(items)} items, to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
